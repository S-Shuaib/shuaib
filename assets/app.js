const N = {
  ai: "AI & emerging tech",
  cyber: "Cybersecurity",
  policy: "Digital policy",
  inclusion: "Inclusion & development",
  society: "Technology & society",
};
const FEATURED = [
  "Giving AI a Nigerian accent: Inside the first local-language model",
  "Nigeria’s sovereign cloud moment: Securing the infrastructure behind the digital economy",
  "Nigeria’s Cybersecurity Pivot: Strategy, Stakes, and the Road Ahead",
  "The cost of hosting Nigeria’s data abroad",
  "Towards Achieving 95% Digital Literacy in Nigeria by 2030",
  "Why Nigeria’s Digital Future Hinges on Culture, Not Code",
];
const esc = s =>
  String(s).replace(
    /[&<>"']/g,
    x =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#039;",
      })[x]
  );
const slug = s =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

function card(x, featured = false) {
  return `<article class="work-card ${featured ? "featured-card" : ""}">
    <div class="card-top"><span class="tag">${N[x.c]}</span><span class="year">${x.y}</span></div>
    <h3>${esc(x.t)}</h3><p>${esc(x.d)}</p>
    <div class="work-bottom"><span class="outlet-count">${x.l.length} ${x.l.length === 1 ? "published version" : "published versions"}</span><div class="article-links">${x.l.map(([n, u]) => `<a href="${esc(u)}" target="_blank" rel="noopener noreferrer">${esc(n)} <span>↗</span></a>`).join("")}</div></div>
  </article>`;
}

function render(filter = "all", query = "") {
  const grid = document.querySelector("#work-grid");
  const q = query.trim().toLowerCase();
  const items = WORK.filter(
    x =>
      (filter === "all" || x.c === filter) &&
      (!q || (x.t + " " + x.d + " " + N[x.c]).toLowerCase().includes(q))
  );
  grid.innerHTML = items.length
    ? items.map(x => card(x)).join("")
    : `<div class="empty"><strong>No stories found.</strong><span>Try another keyword or clear the filters.</span></div>`;
  const count = document.querySelector("#result-count");
  if (count)
    count.textContent = `Showing ${items.length} of ${WORK.length} stories`;
}

function renderFeatured() {
  const grid = document.querySelector("#featured-grid");
  grid.innerHTML = FEATURED.map(title => {
    const x = WORK.find(w => w.t === title);
    return x ? card(x, true) : "";
  }).join("");
}

function init() {
  const years = [...new Set(WORK.map(x => x.y))].sort().reverse();
  const yearSelect = document.querySelector("#year-filter");
  years.forEach(y =>
    yearSelect.insertAdjacentHTML(
      "beforeend",
      `<option value="${y}">${y}</option>`
    )
  );
  const apply = () => {
    const active =
      document.querySelector(".filter.active")?.dataset.filter || "all";
    const year = yearSelect.value;
    const query = document.querySelector("#search").value;
    const q = query.trim().toLowerCase();
    const grid = document.querySelector("#work-grid");
    let items = WORK.filter(
      x =>
        (active === "all" || x.c === active) &&
        (!year || x.y === year) &&
        (!q || (x.t + " " + x.d + " " + N[x.c]).toLowerCase().includes(q))
    ).sort((a, b) => Number(b.y) - Number(a.y));
    grid.innerHTML = items.length
      ? items.map(x => card(x)).join("")
      : `<div class="empty"><strong>No stories found.</strong><span>Try another keyword or clear the filters.</span></div>`;
    document.querySelector("#result-count").textContent =
      `Showing ${items.length} of ${WORK.length} stories`;
  };
  document.querySelectorAll(".filter").forEach(b =>
    b.addEventListener("click", () => {
      document
        .querySelectorAll(".filter")
        .forEach(x => x.classList.remove("active"));
      b.classList.add("active");
      apply();
    })
  );
  document.querySelector("#search").addEventListener("input", apply);
  yearSelect.addEventListener("change", apply);
  document.querySelector("#clear-filters").addEventListener("click", () => {
    document
      .querySelectorAll(".filter")
      .forEach(x => x.classList.remove("active"));
    document.querySelector('[data-filter="all"]').classList.add("active");
    document.querySelector("#search").value = "";
    yearSelect.value = "";
    apply();
  });
  const menu = document.querySelector(".menu"),
    links = document.querySelector(".links");
  menu.addEventListener("click", () => {
    const open = links.classList.toggle("open");
    menu.setAttribute("aria-expanded", open);
  });
  links
    .querySelectorAll("a")
    .forEach(a =>
      a.addEventListener("click", () => links.classList.remove("open"))
    );
  document.querySelector("#total-stories").textContent = WORK.length;
  document.querySelector("#total-outlets").textContent =
    new Set(WORK.flatMap(x => x.l.map(a => a[0]))).size + "+";
  renderFeatured();
  apply();
}
document.addEventListener("DOMContentLoaded", init);
